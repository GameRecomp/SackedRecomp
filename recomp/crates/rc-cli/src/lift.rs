//! `recomp lift`: discovery, then every function to IR and C.
//!
//! One directory per binary below `generated/<game>/` (the code map's directory): `funcs.h`,
//! `code_XXXX.c` (64 KiB of guest code each), `table.c` (the sorted dispatch table) and
//! `binary.c` (the `rc_generated_binary` record). Then `generated/<game>/set.c` lists every
//! binary lifted for the game so far, so the game shell links them all and picks by hash.
//! The output depends only on the binary and the manifest. A FILE may also be an installed
//! folder: then every binary in it that the manifest lifts is lifted (what the build runs, see
//! `cmake/lift.cmake`). Only files whose content changed are written, so a build compiles
//! only those again.

use crate::discover::{default_out, load, Loaded};
use rc_manifest::{Manifest, Role, Treatment};
use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

pub struct LiftOpts<'a> {
    pub games: &'a Path,
    pub out: Option<&'a Path>,
    /// Also write a set of just the binaries of this run (one build target's).
    pub set: Option<&'a Path>,
    pub base: Option<u32>,
    pub comments: bool,
    pub verbose: bool,
}

/// A C identifier from a directory name: `cultures.exe-gog-en` → `cultures_exe_gog_en`.
fn symbol(dir: &str) -> String {
    let s: String = dir
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '_'
            }
        })
        .collect();
    if s.starts_with(|c: char| c.is_ascii_digit()) {
        format!("b_{s}")
    } else {
        s
    }
}

/// Labels that need an entry of their own: addresses inside a function that the program
/// takes as values (SEH handlers, code pointers), except jump-table targets, which the lifted
/// `switch` reaches. Returns `(label, owner)`.
pub use rc_convert::lift::lift_map;

const HEADER: &str = "/* Generated by recomp from the user's own copy of the game.\n * Derived from the game's executable: never commit or distribute. */\n";

fn binary_c(l: &Loaded, sym: &str, count: usize) -> String {
    let (name, variant) = match &l.known {
        Some(k) => (
            k.binary.name.clone(),
            k.binary.variants.first().cloned().unwrap_or_default(),
        ),
        None => (l.map.binary.name.clone(), String::new()),
    };
    format!(
        "{HEADER}#include \"rc/game.h\"\n\n\
         extern const rc_fn_entry {sym}_table[];\n\n\
         const rc_generated_binary {sym}_binary = {{\n    \"{name}\",\n    \"{variant}\",\n    \"{}\",\n    {:#010x}u,\n    {:#010x}u,\n    {sym}_table,\n    {count}u,\n}};\n",
        l.sha256, l.image.base, l.image.entry
    )
}

/// The C of a set: the binaries in the directories `dirs` (names below `generated/<game>/`), as
/// `rc_generated_<game>`. Each directory is also named in a `/* dir: NAME */` line, which the
/// build reads (`cmake/lift.cmake`).
fn set_source(game: &str, dirs: &[String]) -> String {
    let syms: Vec<String> = dirs.iter().map(|d| symbol(d)).collect();
    let mut s = format!("{HEADER}#include \"rc/game.h\"\n\n");
    for d in dirs {
        s.push_str(&format!("/* dir: {d} */\n"));
    }
    s.push('\n');
    for sym in &syms {
        s.push_str(&format!("extern const rc_generated_binary {sym}_binary;\n"));
    }
    s.push_str("\nstatic const rc_generated_binary *const binaries[] = {\n");
    for sym in &syms {
        s.push_str(&format!("    &{sym}_binary,\n"));
    }
    if syms.is_empty() {
        s.push_str("    0,\n");
    }
    s.push_str(&format!(
        "}};\n\nconst rc_generated_set rc_generated_{} = {{\"{game}\", {}, binaries}};\n",
        symbol(game),
        syms.len()
    ));
    s
}

/// `set.c` for the game: every sibling directory with a `binary.c`.
fn write_set(game_dir: &Path, game: &str) -> Result<usize, String> {
    let mut dirs: Vec<String> = fs::read_dir(game_dir)
        .map_err(|e| format!("{}: {e}", game_dir.display()))?
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.join("binary.c").is_file())
        .filter_map(|p| p.file_name().and_then(|n| n.to_str()).map(String::from))
        .collect();
    dirs.sort();
    write_if_changed(&game_dir.join("set.c"), &set_source(game, &dirs))?;
    Ok(dirs.len())
}

/// Write `text` to `path` unless the file already holds exactly that, so that its time stays
/// and a build does not compile it again. Returns whether it was written.
fn write_if_changed(path: &Path, text: &str) -> Result<bool, String> {
    if fs::read(path).is_ok_and(|old| old == text.as_bytes()) {
        return Ok(false);
    }
    fs::write(path, text).map_err(|e| format!("{}: {e}", path.display()))?;
    Ok(true)
}

/// Replace the generated C of one binary: write the files that changed and remove the ones
/// that are no longer generated (a function that moved to another 64 KiB bucket leaves no
/// stale file behind). Returns the bytes of C and how many files were written.
fn write_tree(dir: &Path, tree: &BTreeMap<String, String>) -> Result<(u64, usize), String> {
    fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    for e in fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))? {
        let p = e.map_err(|e| e.to_string())?.path();
        let ext = p.extension().and_then(|x| x.to_str());
        let name = p.file_name().and_then(|n| n.to_str()).unwrap_or_default();
        if matches!(ext, Some("c" | "h")) && !tree.contains_key(name) {
            fs::remove_file(&p).map_err(|e| format!("{}: {e}", p.display()))?;
        }
    }
    let mut bytes = 0u64;
    let mut written = 0;
    for (name, text) in tree {
        written += usize::from(write_if_changed(&dir.join(name), text)?);
        bytes += text.len() as u64;
    }
    Ok((bytes, written))
}

/// `name` in `dir`, matched without case.
pub fn find_file(dir: &Path, name: &str) -> Option<PathBuf> {
    fs::read_dir(dir)
        .ok()?
        .filter_map(Result::ok)
        .map(|e| e.path())
        .find(|p| {
            p.file_name()
                .and_then(|n| n.to_str())
                .is_some_and(|n| n.eq_ignore_ascii_case(name))
        })
}

/// The game and variant an installed folder holds, by the hash of an executable (the main one
/// first). DLLs only as a last resort: the same `binkw32.dll` ships with several games.
pub fn identify_dir<'a>(ms: &'a [Manifest], dir: &Path) -> Option<(&'a Manifest, String)> {
    let rank = |r: Role| match r {
        Role::Main => 0,
        Role::Library => 2,
        _ => 1,
    };
    for pass in 0..3 {
        for m in ms {
            for b in m.binaries.iter().filter(|b| rank(b.role) == pass) {
                let Some(p) = find_file(dir, &b.name) else {
                    continue;
                };
                let Ok(sha) = rc_manifest::sha256_file(&p) else {
                    continue;
                };
                if sha == b.sha256 {
                    if let Some(v) = b.variants.first() {
                        return Some((m, v.clone()));
                    }
                }
            }
        }
    }
    None
}

/// The binaries in an installed folder that the manifest lifts for its variant.
pub fn liftable_in(ms: &[Manifest], dir: &Path) -> Result<Vec<PathBuf>, String> {
    let (m, variant) = identify_dir(ms, dir)
        .ok_or_else(|| format!("{}: no known executable in it", dir.display()))?;
    let mut files: Vec<PathBuf> = Vec::new();
    for b in m
        .binaries
        .iter()
        .filter(|b| b.treatment == Treatment::Lift && b.variants.contains(&variant))
    {
        if let Some(p) = find_file(dir, &b.name) {
            if !files.contains(&p) {
                files.push(p);
            }
        }
    }
    if files.is_empty() {
        return Err(format!("{}: nothing to lift", dir.display()));
    }
    Ok(files)
}

/// The FILEs with every folder replaced by the binaries in it that the manifest lifts.
pub(crate) fn expand(games: &Path, paths: &[PathBuf]) -> Result<Vec<PathBuf>, String> {
    if !paths.iter().any(|p| p.is_dir()) {
        return Ok(paths.to_vec());
    }
    let ms = rc_manifest::load_dir(games).map_err(|e| e.to_string())?;
    let mut files = Vec::new();
    for p in paths {
        if p.is_dir() {
            files.extend(liftable_in(&ms, p)?);
        } else {
            files.push(p.clone());
        }
    }
    Ok(files)
}

pub use rc_convert::lift::apply_patches;

pub fn lift(o: &LiftOpts, paths: &[PathBuf]) -> Result<ExitCode, String> {
    if paths.is_empty() {
        return Err("lift needs at least one FILE".into());
    }
    let files = expand(o.games, paths)?;
    let mut this_run: Vec<(String, String)> = Vec::new(); // (game, directory)
    if o.out.is_some() && files.len() > 1 {
        return Err("--out works with one FILE only".into());
    }
    for (n, file) in files.iter().enumerate() {
        if n > 0 {
            println!();
        }
        let l = load(file, o.games, o.base, true)?;
        if let Some(k) = l
            .known
            .as_ref()
            .filter(|k| k.binary.treatment == Treatment::Ignore)
        {
            // Not part of the recompiled game (installer helpers, GOG's own wrappers): a lifted
            // copy would join the game's set and replace what the runtime provides.
            println!(
                "{}: skipped, the manifest does not lift {} (treatment \"ignore\")",
                file.display(),
                k.binary.name
            );
            continue;
        }
        let dir = o
            .out
            .map_or_else(|| default_out(o.games, &l), Path::to_path_buf);
        let dir_name = dir
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or("binary")
            .to_string();
        let sym = symbol(&dir_name);
        let mut lifted = lift_map(&l);
        if let Some(k) = &l.known {
            apply_patches(&mut lifted.functions, &k.binary.patch)
                .map_err(|e| format!("{}: {e}", file.display()))?;
        }
        let entries: BTreeSet<u32> = lifted.functions.iter().map(|f| f.addr).collect();
        let names = rc_emit_c::Entries {
            prefix: format!("{sym}_"),
            entries,
        };
        let opts = rc_emit_c::Options {
            comments: o.comments,
            ..rc_emit_c::Options::default()
        };
        let mut tree = rc_emit_c::binary(&names, &lifted.functions, &sym, opts);
        tree.insert(
            "binary.c".into(),
            binary_c(&l, &sym, lifted.functions.len()),
        );
        let json = serde_json::to_string_pretty(&l.map).map_err(|e| e.to_string())?;
        let (bytes, written) = write_tree(&dir, &tree)?;
        if let Some(game) = dir
            .parent()
            .and_then(|p| p.file_name())
            .and_then(|n| n.to_str())
        {
            if !this_run.iter().any(|(_, d)| *d == dir_name) {
                this_run.push((game.to_string(), dir_name.clone()));
            }
        }
        write_if_changed(&dir.join("codemap.json"), &(json + "\n"))?;

        let traps: u32 = lifted.traps.values().sum();
        println!("binary      {} ({})", l.map.binary.name, &l.sha256[..16]);
        println!(
            "lifted      {} functions ({} of them label entries), {} instructions",
            lifted.functions.len(),
            lifted.label_entries,
            lifted.instructions
        );
        println!(
            "traps       {traps} instructions in {} kinds",
            lifted.traps.len()
        );
        let mut by_count: Vec<(&String, &u32)> = lifted.traps.iter().collect();
        by_count.sort_by(|a, b| b.1.cmp(a.1).then(a.0.cmp(b.0)));
        let shown = if o.verbose { by_count.len() } else { 12 };
        for (why, k) in by_count.iter().take(shown) {
            println!("  {k:>6}  {why}");
        }
        if by_count.len() > shown {
            println!(
                "  …       {} more kinds (--verbose)",
                by_count.len() - shown
            );
        }
        println!(
            "C           {} files ({written} changed), {:.1} MB in {}",
            tree.len(),
            bytes as f64 / 1e6,
            dir.display()
        );
        if let (Some(game_dir), Some(game)) = (
            dir.parent(),
            dir.parent()
                .and_then(|p| p.file_name())
                .and_then(|n| n.to_str()),
        ) {
            if o.out.is_none() {
                let n = write_set(game_dir, game)?;
                println!(
                    "set         {n} lifted binaries in {}",
                    game_dir.join("set.c").display()
                );
            }
        }
    }
    if let Some(path) = o.set {
        let Some((game, _)) = this_run.first() else {
            return Err("--set: nothing was lifted".into());
        };
        if this_run.iter().any(|(g, _)| g != game) {
            return Err("--set: the binaries belong to different games".into());
        }
        let mut dirs: Vec<String> = this_run.iter().map(|(_, d)| d.clone()).collect();
        dirs.sort();
        if let Some(parent) = path.parent().filter(|p| !p.as_os_str().is_empty()) {
            fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
        }
        write_if_changed(path, &set_source(game, &dirs))?;
        println!(
            "set         {} binaries of this run in {}",
            dirs.len(),
            path.display()
        );
    }
    Ok(ExitCode::SUCCESS)
}

